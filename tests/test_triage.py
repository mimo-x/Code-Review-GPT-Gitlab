def plan_for(repository, tmp_path, before: dict, after: dict, config=None):
    for path, text in before.items():
        repository.write(path, text)
    base = repository.commit("base")
    for path, text in after.items():
        if text is None:
            (repository.path / path).unlink()
        else:
            repository.write(path, text)
    head = repository.commit("head")
    workspace = Workspace.create(repository.path, tmp_path / "state", "p", base, head)
    intel = CodeIntel(workspace)
    return Triage(intel, config).plan(), intel


def members(plan, intel):
    units = {unit.id: unit for unit in intel.changed_symbols()}
    return [
        {units[key].new_path or units[key].old_path for key in cluster.unit_ids}
        for cluster in plan.clusters
    ]


def test_plan_is_deterministic_complete_and_stored(reviewed):
    _, workspace, intel = reviewed
    plan = Triage(intel).plan()
    assert len(plan.clusters) == 1
    assert {link.kind for link in plan.clusters[0].links} >= {"call", "test_reference"}
    assert plan.coverage.reviewed_units == len(intel.changed_symbols())
    assert plan.coverage.exclusions == ()
    assert all(cluster.budget_tokens >= plan.config.floor_tokens for cluster in plan.clusters)
    assert plan.total_tokens == plan.pool_tokens + sum(c.budget_tokens for c in plan.clusters)
    assert Triage(CodeIntel(workspace)).plan() == plan
    assert Triage(intel).load(plan.id) == plan
    assert plan.cluster("C1") == plan.clusters[0]
    with pytest.raises(ReviewCoreError, match="not found"):
        Triage(intel).load("missing")


def test_hard_evidence_exclusions_and_coverage(repository, tmp_path):
    js = "function add(a, b) {\n  return a + b;\n}\n"
    py = "def run(flag):\n    if flag:\n        return 1\n    return 2\n"
    before = {
        "package-lock.json": '{"a": 1}\n',
        "app.min.js": "var a=1;\n",
        "gen.py": "# Code generated by tool. DO NOT EDIT.\nvalue = 1\n",
        "logo.png": b"\x89PNG\0\0old",
        "format.js": js,
        "trailing.py": "value = 1\n",
        "indent.py": py,
        "notes.md": "line\n",
    }
    after = {
        "package-lock.json": '{"a": 2}\n',
        "app.min.js": "var a=2;\n",
        "gen.py": "# Code generated by tool. DO NOT EDIT.\nvalue = 2\n",
        "logo.png": b"\x89PNG\0\0new",
        "format.js": "function add(a,b){\n    return a+b;\n}\n",
        "trailing.py": "value = 1   \n",
        # Re-indenting the last return moves it into the if-block: a semantic change.
        "indent.py": py.replace("    return 2", "        return 2"),
        "notes.md": "line  \n",
    }
    plan, intel = plan_for(repository, tmp_path, before, after)
    reasons = {item.path: item.reason for item in plan.coverage.exclusions}
    assert reasons == {
        "package-lock.json": "lock_file",
        "app.min.js": "minified",
        "gen.py": "generated",
        "logo.png": "binary",
        "format.js": "format_only",
        "trailing.py": "format_only",
    }
    reviewed = {path for group in members(plan, intel) for path in group}
    assert reviewed == {"indent.py", "notes.md"}
    total = sum(len(unit.lines) for unit in intel.changed_symbols())
    assert plan.coverage.reviewed_lines + plan.coverage.excluded_lines == total
    assert "Excluded" in plan.catalog and "package-lock.json (lock_file)" in plan.catalog


def test_languages_without_bound_edges_still_group_by_file_and_mentions(repository, tmp_path):
    def go(body):
        return "package calc\n\n" + body

    funcs = "".join(f"func F{i}() int {{\n\treturn {i}\n}}\n\n" for i in range(9))
    before = {
        "calc/many.go": go(funcs),
        "calc/total.go": go("func ComputeTotal(a int) int {\n\treturn a\n}\n"),
        "api/handler.go": "package api\n\nfunc Handle() int {\n\treturn 1\n}\n",
        "calc/total_test.go": go("func TestTotal(t *T) {\n\t_ = 1\n}\n"),
    }
    after = {
        "calc/many.go": go(funcs.replace("return ", "return 10 + ")),
        "calc/total.go": go("func ComputeTotal(a int) int {\n\treturn a * 2\n}\n"),
        "api/handler.go": "package api\n\nfunc Handle() int {\n\treturn calc.ComputeTotal(1)\n}\n",
        "calc/total_test.go": go("func TestTotal(t *T) {\n\t_ = 2\n}\n"),
    }
    plan, intel = plan_for(repository, tmp_path, before, after)
    groups = members(plan, intel)
    assert {"calc/many.go"} <= next(group for group in groups if "calc/many.go" in group)
    joined = next(group for group in groups if "calc/total.go" in group)
    assert {"api/handler.go", "calc/total_test.go"} <= joined
    kinds = {link.kind for cluster in plan.clusters for link in cluster.links}
    assert {"mention", "test_pair", "same_file"} <= kinds


def unit(name, lines=10, path=None, kind="source"):
    return ChangeUnit(
        id=name,
        file_change_id=name,
        old_path=path or f"{name}.py",
        new_path=path or f"{name}.py",
        base_symbol=None,
        head_symbol=None,
        kinds=("module",),
        lines=tuple(
            DiffLine(
                id=f"{name}-{index}",
                kind="add",
                old_line=None,
                new_line=index + 1,
                text=f"value_{index} = {index}\n",
            )
            for index in range(lines)
        ),
        hunk_ids=(name,),
        classification=FileClassification(
            language="python", kind=kind, parser_available=True, outline_available=True
        ),
    )


def link(a, b, weight):
    left, right = sorted((a, b))
    return Link(
        source=left, target=right, kind="call", confidence="bound", weight=weight, basis="t"
    )


def test_clustering_is_strongest_first_capacity_bounded_and_order_free():
    units = tuple(unit(name) for name in "ABCDE")
    sizes = {"A": 400, "B": 400, "C": 400, "D": 400, "E": 7000}
    links = (link("A", "B", 1.0), link("B", "C", 0.5), link("C", "D", 0.4), link("D", "E", 1.0))
    config = TriageConfig(max_cluster_tokens=1000, pack_tokens=0)
    ordered = sorted(links, key=lambda item: (-item.weight, item.source, item.target))
    groups = cluster_units(units, tuple(ordered), sizes, config)
    assert [members for members, _ in groups] == [("A", "B"), ("C", "D"), ("E",)]
    assert [len(internal) for _, internal in groups] == [1, 1, 0]
    shuffled = list(units)
    random.Random(3).shuffle(shuffled)
    assert cluster_units(tuple(shuffled), tuple(ordered), sizes, config) == groups
    capped = cluster_units(
        units, tuple(ordered), sizes, TriageConfig(max_cluster_units=1, pack_tokens=0)
    )
    assert len(capped) == 5


def test_small_unlinked_changes_pack_by_path_within_top_directory():
    paths = ["src/a/x.py", "src/a/y.py", "src/b/z.py", "web/q.ts", "web/r.ts", "big/w.py"]
    units = tuple(unit(f"u{i}", path=path) for i, path in enumerate(paths))
    sizes = {"u0": 300, "u1": 300, "u2": 300, "u3": 300, "u4": 300, "u5": 5000}
    groups = cluster_units(units, (), sizes, TriageConfig(pack_tokens=1000))
    assert [members for members, _ in groups] == [("u0", "u1", "u2"), ("u3", "u4"), ("u5",)]
    assert {link.kind for _, internal in groups for link in internal} == {"locality"}
    assert len(cluster_units(units, (), sizes, TriageConfig(pack_tokens=0))) == 6


def test_many_independent_changes_are_never_deferred(repository, tmp_path):
    before = {f"pkg{i}/mod.py": f"def f{i}():\n    return {i}\n" for i in range(40)}
    after = {f"pkg{i}/mod.py": f"def f{i}():\n    return {i + 1}\n" for i in range(40)}
    config = TriageConfig(max_cluster_tokens=256)
    plan, _ = plan_for(repository, tmp_path, before, after, config)
